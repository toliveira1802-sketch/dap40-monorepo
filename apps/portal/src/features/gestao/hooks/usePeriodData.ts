function sliceByPeriod<T>(data: T[], months: number): T[] {
  if (months === 0) return data.slice(-1);
  if (months >= data.length) return data;
  return data.slice(-months);
}

export function usePeriodData() {
  const { periodOption } = usePeriod();
  const months = periodOption.months;

  return {
    monthlyRevenue: sliceByPeriod(fullMonthlyRevenue, months),
    timeline: sliceByPeriod(fullTimeline, months),
    fluxo: sliceByPeriod(fullFluxo, months),
    headcount: sliceByPeriod(fullHeadcount, months),
    uptime: sliceByPeriod(fullUptime, months),
    tempo: sliceByPeriod(fullTempo, months),
    clienteEvol: sliceByPeriod(fullClienteEvol, months),
    trilhas: sliceByPeriod(fullTrilhas, months),
  };
}
